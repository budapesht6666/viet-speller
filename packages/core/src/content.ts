/**
 * Модель контента (PLAN.md, этап 3). Типы живут в ядре, а не в
 * `packages/content`: движок урока и правила ачивок работают с ними так же,
 * как контент, и тянуть контент в ядро ради типов было бы зависимостью
 * в обратную сторону.
 */

/** Где говорят по-другому. Значение — как говорят там. */
export interface Dialect {
  north?: string;
  south?: string;
  center?: string;
}

/**
 * Слово — лексическая единица, в том числе составная (`cà phê`,
 * `năm mươi nghìn`). Фраза — высказывание из слов: каждое её слово обязано
 * быть введено раньше или в том же уроке, это проверяет тест контента.
 */
export type ItemKind = 'word' | 'phrase';

/** Слово или фраза — единица урока и карточка повторения. */
export interface Item {
  /** Стабильный: на него ссылаются журнал событий и карточки FSRS. */
  id: string;
  /** То, что озвучивается и показывается. */
  vi: string;
  ru: string;
  kind: ItemKind;
  /** Засчитывается наравне с `vi`. Там, где допустимы два ответа, человек прав. */
  alt?: string[];
  /** Расхождение выговоров пишется явно, а не выбирается молча. */
  dialect?: Dialect;
  /** Короткое «почему так» — написано заранее, а не генерируется. */
  note?: string;
  /** Имя иконки Streamline. Необязательна: натянутая картинка хуже, чем никакой. */
  icon?: string;
}

export interface Lesson {
  /** Стабильный, как и id элемента: на него ссылается журнал. */
  id: string;
  title: string;
  /** Новые элементы урока по порядку появления. Каждый вводится ровно в одном уроке. */
  items: string[];
  /**
   * Тренировка тонов: варианты в вопросе нарочно отличаются только тоном.
   * Во всех остальных уроках такие варианты в один вопрос не ставятся.
   */
  toneDrill?: boolean;
  /**
   * Только на слух и касания. Одиночные звуки и тоны голосом не проверяем:
   * замер не ответил, честно ли движок пишет тон и узнаёт ли слог
   * (PLAN.md, этап 0).
   */
  listenOnly?: boolean;
}

export interface Topic {
  id: string;
  title: string;
  /** Одна строка под названием на экране пути. */
  summary: string;
  lessons: Lesson[];
}
